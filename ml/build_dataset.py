"""Build the labelled training cohort used by the hybrid fitness model.

Provenance
----------
The base cohort is the public **"Gym Members Exercise Dataset"** by Vala
Khorasani (Kaggle). It contains 973 real workout sessions with physiological
columns (age, gender, weight, height, BMI, body fat, heart rates, session
duration, calories burned, water intake, days trained per week, experience
level). The raw file is mirrored at
``config.RAW_DATASET_URL`` and cached in ``ml/data/raw/``.

The public dataset does not contain the lifestyle attributes the application
knows about (goal, motivation, diet quality, sleep, skipped sessions, ...) so
those attributes are generated by a **seeded, documented simulator** that is
conditioned on the real row: a trainee with 30 % body fat is far more likely
to be a fat-loss goal than a trainee with 12 %, and so on. A second block of
fully simulated rows is appended so that the rarer habit classes (sedentary
struggler, overtraining risk) and the home / outdoor equipment profiles are
represented as well.

The result is written to ``ml/data/fitness_habits.csv`` — the single labelled
CSV that both models are trained on. Labels are produced by the transparent
rules in :mod:`ml.labels` plus a small amount of label noise so the task is
not perfectly separable.

Run it with::

    python -m ml.build_dataset
"""

from __future__ import annotations

import argparse
import sys
import urllib.request
from pathlib import Path
from typing import Dict

import numpy as np
import pandas as pd

if __package__ in (None, ""):  # pragma: no cover - direct execution support
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ml.config import (  # noqa: E402
    ACTIVITY_LEVELS,
    DATA_DIR,
    EQUIPMENT,
    PREFERRED_FOCUS,
    RANDOM_STATE,
    RAW_DATASET_PATH,
    RAW_DATASET_URL,
    TRAINING_DATASET_PATH,
)
from ml.labels import label_habit_category, label_recommended_category  # noqa: E402

HABIT_LABEL_NOISE = 0.06
RECOMMENDATION_LABEL_NOISE = 0.04
SIMULATED_ROW_COUNT = 760
MISSING_RATE_NUMERIC = 0.05
MISSING_RATE_CATEGORICAL = 0.02

SESSION_LENGTH_OPTIONS = [30, 45, 60, 75, 90]

GOAL_BY_EXPERIENCE_BIAS = {
    "beginner": {"loss": 0.34, "muscle": 0.22, "endurance": 0.22, "health": 0.22},
    "intermediate": {"loss": 0.32, "muscle": 0.30, "endurance": 0.20, "health": 0.18},
    "advanced": {"loss": 0.26, "muscle": 0.42, "endurance": 0.16, "health": 0.16},
}


# --------------------------------------------------------------------------- #
# Raw data
# --------------------------------------------------------------------------- #
def ensure_raw_dataset(force: bool = False) -> Path:
    """Return the path of the cached raw CSV, downloading it when missing."""
    RAW_DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    if RAW_DATASET_PATH.exists() and not force:
        return RAW_DATASET_PATH
    print(f"Downloading the raw cohort from {RAW_DATASET_URL}")
    with urllib.request.urlopen(RAW_DATASET_URL, timeout=60) as response:
        payload = response.read()
    RAW_DATASET_PATH.write_bytes(payload)
    return RAW_DATASET_PATH


def load_raw() -> pd.DataFrame:
    path = ensure_raw_dataset()
    df = pd.read_csv(path)
    df.columns = [c.strip() for c in df.columns]
    return df


def normalise_real_rows(raw: pd.DataFrame) -> pd.DataFrame:
    """Map the public dataset columns onto the project's feature schema."""
    df = pd.DataFrame()
    df["age"] = raw["Age"].astype(float).round()
    df["sex"] = raw["Gender"].astype(str).str.strip().str.lower()
    df["weight_kg"] = raw["Weight (kg)"].astype(float).round(1)
    df["height_cm"] = (raw["Height (m)"].astype(float) * 100).round()
    df["bmi"] = raw["BMI"].astype(float).round(1)
    df["body_fat_pct"] = raw["Fat_Percentage"].astype(float).round(1)
    df["resting_bpm"] = raw["Resting_BPM"].astype(float)
    df["max_bpm"] = raw["Max_BPM"].astype(float)
    df["avg_bpm"] = raw["Avg_BPM"].astype(float)
    df["session_duration_min"] = (raw["Session_Duration (hours)"].astype(float) * 60).round()
    df["calories_burned"] = raw["Calories_Burned"].astype(float).round(0)
    df["water_glasses"] = (raw["Water_Intake (liters)"].astype(float) * 4).round()
    df["workouts_per_week"] = raw["Workout_Frequency (days/week)"].astype(float)
    df["source_workout_type"] = raw["Workout_Type"].astype(str).str.strip()
    df["experience_num"] = raw["Experience_Level"].astype(float)
    df["experience_level"] = df["experience_num"].map(
        {1.0: "beginner", 2.0: "intermediate", 3.0: "advanced"}
    )
    df["row_source"] = "real_public_dataset"
    return df.reset_index(drop=True)


# --------------------------------------------------------------------------- #
# Lifestyle simulation
# --------------------------------------------------------------------------- #
def _sample_goal(
    rng: np.random.Generator,
    sex: str,
    age: float,
    bmi: float,
    fat_pct: float,
    workout_type: str,
    experience: str,
) -> str:
    fat_threshold = 22 if sex == "male" else 30
    fat_high = fat_pct >= fat_threshold
    heavy = bmi >= 28
    strength_type = workout_type in ("Strength", "Functional")
    cardio_type = workout_type in ("Cardio", "HIIT")
    yoga_type = workout_type == "Yoga"
    young_male = sex == "male" and age < 30

    weights = {
        "loss": 0.10 + 0.34 * fat_high + 0.08 * strength_type + 0.08 * heavy,
        "muscle": 0.10 + 0.20 * strength_type + 0.16 * (experience == "advanced") + 0.08 * young_male,
        "endurance": 0.10 + 0.20 * cardio_type + 0.10 * yoga_type,
        "health": 0.16,
    }
    bias = GOAL_BY_EXPERIENCE_BIAS[experience]
    for goal, extra in bias.items():
        weights[goal] += 0.06 * extra
    total = sum(weights.values())
    probs = np.array([weights[g] / total for g in ("loss", "muscle", "endurance", "health")])
    return str(rng.choice(["loss", "muscle", "endurance", "health"], p=probs))


def _simulate_lifestyle(
    rng: np.random.Generator,
    *,
    sex: str,
    age: float,
    bmi: float,
    fat_pct: float,
    workout_type: str,
    experience: str,
    frequency: float,
    session_duration_min: float,
    archetype: str,
) -> Dict[str, object]:
    """Generate the lifestyle attributes the app knows about for one person."""
    goal = _sample_goal(rng, sex, age, bmi, fat_pct, workout_type, experience)

    goal_days = {"loss": 3, "muscle": 4, "endurance": 3, "health": 3}[goal]
    planned = goal_days + (1 if experience == "advanced" else 0)
    planned += int(rng.integers(-1, 2))
    if archetype == "sedentary":
        planned = int(rng.integers(2, 4))
    elif archetype == "heavy":
        planned = 6
    planned = int(np.clip(max(planned, frequency), 2, 6))

    skipped = max(0, planned - frequency) + int(rng.integers(0, 2))
    if archetype == "sedentary":
        skipped = int(rng.integers(2, 6))

    diet_quality = float(np.clip(rng.normal(5.4, 1.5) + (1.0 if goal in ("loss", "muscle") else 0.0), 1, 10))
    protein_meals = int(np.clip(round(diet_quality / 1.9 + rng.normal(0, 0.8)), 0, 6))
    junk_food = int(np.clip(round(13.5 - diet_quality * 1.3 + rng.normal(0, 2.6)), 0, 21))

    sleep_quality = 0.0
    if archetype == "heavy":
        sleep_quality = -1.4
    elif archetype == "sedentary":
        sleep_quality = -0.4
    sleep_hours = float(np.clip(rng.normal(7.1, 0.9) + sleep_quality, 4.5, 9.5))

    steps_base = {"sedentary": 3200, "light": 5200, "moderate": 8200, "committed": 10500, "heavy": 11500}
    daily_steps = int(np.clip(rng.normal(steps_base.get(archetype, 7000), 1800), 1200, 22000))

    motivation = float(np.clip(rng.normal(5.4, 1.7) + (1.3 if archetype == "committed" else 0.0), 1, 10))
    if goal == "muscle" and archetype == "committed":
        motivation = float(np.clip(motivation + 0.6, 1, 10))

    tracks_progress = int(rng.random() < 0.30 + 0.06 * (experience == "advanced") + 0.03 * (motivation >= 7))
    screen_before_bed = int(rng.random() < float(np.clip(0.62 - 0.045 * (sleep_hours - 5.0), 0.08, 0.85)))

    equipment_weights = {
        "full_gym": 0.42 if workout_type in ("Strength", "HIIT", "Functional") else 0.28,
        "basic_gym": 0.26,
        "home": 0.18,
        "outdoor": 0.10,
    }
    if archetype == "sedentary":
        equipment_weights = {"full_gym": 0.18, "basic_gym": 0.22, "home": 0.36, "outdoor": 0.24}
    eq_keys = list(equipment_weights)
    eq_total = sum(equipment_weights.values())
    equipment = str(rng.choice(eq_keys, p=[equipment_weights[k] / eq_total for k in eq_keys]))

    if daily_steps < 4500:
        activity_level = "sedentary"
    elif daily_steps < 7500:
        activity_level = "light"
    elif daily_steps < 11000:
        activity_level = "moderate"
    else:
        activity_level = "active"
    if rng.random() < 0.18:
        activity_level = str(rng.choice(ACTIVITY_LEVELS))

    focus_map = {
        "Strength": "strength",
        "Functional": "strength",
        "Cardio": "cardio",
        "HIIT": "hiit",
        "Yoga": "mobility",
        "CrossFit": "hiit",
        "Zumba": "cardio",
    }
    preferred_focus = focus_map.get(workout_type, str(rng.choice(PREFERRED_FOCUS)))

    planned_minutes = float(np.clip(round(session_duration_min / 15) * 15, 30, 90))
    if goal == "muscle":
        planned_minutes = min(90, planned_minutes + 15)
    if goal == "health":
        planned_minutes = max(30, planned_minutes - 15)
    session_minutes = float(min(SESSION_LENGTH_OPTIONS, key=lambda opt: abs(opt - planned_minutes)))

    return {
        "fitness_goal": goal,
        "planned_days_per_week": float(planned),
        "skipped_per_week": float(skipped),
        "session_minutes": session_minutes,
        "diet_quality": round(diet_quality, 1),
        "protein_meals": float(protein_meals),
        "junk_food_per_week": float(junk_food),
        "sleep_hours": round(sleep_hours, 1),
        "daily_steps": float(daily_steps),
        "motivation": round(motivation, 1),
        "screen_before_bed": screen_before_bed,
        "tracks_progress": tracks_progress,
        "equipment": equipment,
        "activity_level": activity_level,
        "preferred_focus": preferred_focus,
    }


def _simulate_cohort_rows(rng: np.random.Generator, count: int) -> pd.DataFrame:
    """Fully simulated rows that widen the class and equipment coverage."""
    archetypes = (
        ["sedentary"] * 14
        + ["light"] * 20
        + ["moderate"] * 30
        + ["committed"] * 26
        + ["heavy"] * 10
    )
    rows = []
    for i in range(count):
        archetype = archetypes[i % len(archetypes)]
        sex = str(rng.choice(["male", "female"], p=[0.58, 0.42]))
        age = float(np.clip(rng.normal(31, 10), 16, 68))
        height_cm = float(rng.normal(175 if sex == "male" else 162, 6))
        bmi = float(np.clip(rng.normal(24.6, 4.4), 16.5, 39))
        weight_kg = round(bmi * (height_cm / 100) ** 2, 1)
        fat_base = 14 if sex == "male" else 26
        fat_pct = float(np.clip(rng.normal(fat_base + (bmi - 24.6) * 0.85, 3.4), 6, 45))
        experience_num = int(rng.choice([1, 2, 3], p=[0.42, 0.38, 0.20]))
        experience = {1: "beginner", 2: "intermediate", 3: "advanced"}[experience_num]
        freq_options = {
            "sedentary": [0, 1],
            "light": [1, 2],
            "moderate": [2, 3, 4],
            "committed": [3, 4, 5],
            "heavy": [5, 6],
        }[archetype]
        frequency = float(rng.choice(freq_options))
        session_duration_min = float(
            np.clip(rng.normal(52 if archetype != "sedentary" else 34, 12), 20, 115)
        )
        workout_type = str(
            rng.choice(
                ["Strength", "Cardio", "HIIT", "Yoga", "Functional", "CrossFit", "Zumba"],
                p=[0.28, 0.22, 0.12, 0.10, 0.12, 0.08, 0.08],
            )
        )
        lifestyle = _simulate_lifestyle(
            rng,
            sex=sex,
            age=age,
            bmi=bmi,
            fat_pct=fat_pct,
            workout_type=workout_type,
            experience=experience,
            frequency=frequency,
            session_duration_min=session_duration_min,
            archetype=archetype,
        )
        resting_bpm = float(rng.normal(64 if experience == "advanced" else 70, 7))
        max_bpm = float(np.clip(205 - 0.65 * age + rng.normal(0, 6), 150, 215))
        row = {
            "age": round(age),
            "sex": sex,
            "weight_kg": weight_kg,
            "height_cm": round(height_cm),
            "bmi": round(bmi, 1),
            "body_fat_pct": round(fat_pct, 1),
            "resting_bpm": round(resting_bpm),
            "max_bpm": round(max_bpm),
            "avg_bpm": round(resting_bpm + (max_bpm - resting_bpm) * 0.62),
            "session_duration_min": round(session_duration_min),
            "calories_burned": round(
                float(np.clip(rng.normal(6.2 * weight_kg * (session_duration_min / 60), 90), 90, 2100))
            ),
            "water_glasses": float(rng.integers(4, 17)),
            "workouts_per_week": frequency,
            "source_workout_type": workout_type,
            "experience_num": experience_num,
            "experience_level": experience,
            "row_source": "simulated_cohort",
        }
        row.update(lifestyle)
        rows.append(row)
    return pd.DataFrame(rows)


def _simulate_real_rows(rng: np.random.Generator, real: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, src in real.iterrows():
        archetype = "moderate"
        if src["workouts_per_week"] <= 2:
            archetype = "light"
        elif src["workouts_per_week"] >= 5:
            archetype = "committed"
        lifestyle = _simulate_lifestyle(
            rng,
            sex=str(src["sex"]),
            age=float(src["age"]),
            bmi=float(src["bmi"]),
            fat_pct=float(src["body_fat_pct"]),
            workout_type=str(src["source_workout_type"]),
            experience=str(src["experience_level"]),
            frequency=float(src["workouts_per_week"]),
            session_duration_min=float(src["session_duration_min"]),
            archetype=archetype,
        )
        row = {k: v for k, v in src.items() if k != "experience_num"}
        row.update(lifestyle)
        rows.append(row)
    return pd.DataFrame(rows)


# --------------------------------------------------------------------------- #
# Labels + missing values
# --------------------------------------------------------------------------- #
def apply_labels(df: pd.DataFrame, rng: np.random.Generator) -> pd.DataFrame:
    habit = []
    recommendation = []
    for _, row in df.iterrows():
        habit.append(
            label_habit_category(
                workouts_per_week=float(row["workouts_per_week"]),
                planned_days_per_week=float(row["planned_days_per_week"]),
                sleep_hours=float(row["sleep_hours"]),
                diet_quality=float(row["diet_quality"]),
                motivation=float(row["motivation"]),
                skipped_per_week=float(row["skipped_per_week"]),
            )
        )
        recommendation.append(
            label_recommended_category(
                fitness_goal=str(row["fitness_goal"]),
                experience_level=str(row["experience_level"]),
                workouts_per_week=float(row["workouts_per_week"]),
                session_minutes=float(row["session_minutes"]),
                preferred_focus=str(row["preferred_focus"]),
            )
        )

    from ml.config import HABIT_CATEGORY_META, WORKOUT_CATEGORY_META

    habit_classes = sorted(HABIT_CATEGORY_META)
    rec_classes = sorted(WORKOUT_CATEGORY_META)

    noisy_habit = []
    for label in habit:
        if rng.random() < HABIT_LABEL_NOISE:
            choices = [c for c in habit_classes if c != label]
            label = str(rng.choice(choices))
        noisy_habit.append(label)

    noisy_rec = []
    for label in recommendation:
        if rng.random() < RECOMMENDATION_LABEL_NOISE:
            choices = [c for c in rec_classes if c != label]
            label = str(rng.choice(choices))
        noisy_rec.append(label)

    df = df.copy()
    df["habit_category"] = noisy_habit
    df["recommended_category"] = noisy_rec
    return df


def inject_missing_values(df: pd.DataFrame, rng: np.random.Generator) -> pd.DataFrame:
    """Blank out a small share of cells so the imputation path is exercised."""
    df = df.copy()
    numeric_targets = [
        "diet_quality",
        "protein_meals",
        "junk_food_per_week",
        "sleep_hours",
        "daily_steps",
        "motivation",
        "water_glasses",
        "skipped_per_week",
        "session_minutes",
    ]
    categorical_targets = ["activity_level", "equipment", "preferred_focus"]

    for column in numeric_targets:
        mask = rng.random(len(df)) < MISSING_RATE_NUMERIC
        df.loc[mask, column] = np.nan
    for column in categorical_targets:
        mask = rng.random(len(df)) < MISSING_RATE_CATEGORICAL
        df.loc[mask, column] = None
    return df


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def build_dataset(
    output_path: Path = TRAINING_DATASET_PATH,
    simulated_rows: int = SIMULATED_ROW_COUNT,
    seed: int = RANDOM_STATE,
) -> Path:
    rng = np.random.default_rng(seed)

    raw = load_raw()
    real = normalise_real_rows(raw)
    real_simulated = _simulate_real_rows(rng, real)
    cohort = _simulate_cohort_rows(rng, simulated_rows)
    df = pd.concat([real_simulated, cohort], ignore_index=True)

    df = apply_labels(df, rng)
    df = inject_missing_values(df, rng)

    ordered = [
        "age",
        "sex",
        "height_cm",
        "weight_kg",
        "bmi",
        "body_fat_pct",
        "resting_bpm",
        "avg_bpm",
        "max_bpm",
        "session_duration_min",
        "calories_burned",
        "water_glasses",
        "workouts_per_week",
        "planned_days_per_week",
        "skipped_per_week",
        "session_minutes",
        "fitness_goal",
        "experience_level",
        "equipment",
        "activity_level",
        "preferred_focus",
        "diet_quality",
        "protein_meals",
        "junk_food_per_week",
        "sleep_hours",
        "daily_steps",
        "motivation",
        "screen_before_bed",
        "tracks_progress",
        "source_workout_type",
        "row_source",
        "habit_category",
        "recommended_category",
    ]
    df = df[ordered]
    df = df.sort_values("row_source").reset_index(drop=True)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)

    print(f"Wrote {len(df)} rows x {len(df.columns)} columns to {output_path}")
    print("\nHabit category distribution:")
    print(df["habit_category"].value_counts().to_string())
    print("\nRecommended category distribution:")
    print(df["recommended_category"].value_counts().to_string())
    print(f"\nMissing cells: {int(df.isna().sum().sum())}")
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the labelled training CSV.")
    parser.add_argument("--output", default=str(TRAINING_DATASET_PATH))
    parser.add_argument("--simulated-rows", type=int, default=SIMULATED_ROW_COUNT)
    parser.add_argument("--seed", type=int, default=RANDOM_STATE)
    parser.add_argument(
        "--refresh-raw",
        action="store_true",
        help="Download the raw public dataset again before building.",
    )
    args = parser.parse_args()

    if args.refresh_raw:
        ensure_raw_dataset(force=True)

    build_dataset(Path(args.output), simulated_rows=args.simulated_rows, seed=args.seed)


if __name__ == "__main__":
    main()
